import { QueryClient } from '@tanstack/react-query'

/** Shared QueryClient with conservative defaults for server state. */
export const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      staleTime: 60_000,
      gcTime: 5 * 60_000,
      refetchOnWindowFocus: false,
      retry: 1,
    },
  },
})
